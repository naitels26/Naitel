(() => {
    const langToggleBtn = document.getElementById('lang-toggle');
    let currentLang = 'es';
    try {
        currentLang = localStorage.getItem('lang') === 'en' ? 'en' : 'es';
    } catch { /* Storage may be unavailable in private or restricted contexts. */ }

    langToggleBtn?.addEventListener('click', () => {
        currentLang = currentLang === 'es' ? 'en' : 'es';
        setLanguage(currentLang);
        try { localStorage.setItem('lang', currentLang); } catch { /* Keep working without persistence. */ }
    });
    function setLanguage(lang) {
        document.documentElement.lang = lang;
        if (langToggleBtn) {
            langToggleBtn.textContent = lang === 'es' ? 'EN' : 'ES';
            langToggleBtn.lang = lang === 'es' ? 'en' : 'es';
            langToggleBtn.setAttribute('aria-label', lang === 'es' ? 'Switch to English' : 'Cambiar a español');
        }
        document.querySelectorAll('[data-i18n]').forEach(element => {
            const key = element.dataset.i18n;
            const value = translations[lang][key];
            if (!value) return;
            // The dictionary separates the accent; CSS controls responsive wrapping.
            if (key === 'hero-title') {
                const lines = value.split('<br>');
                const firstLine = document.createElement('span');
                firstLine.className = 'hero-line';
                firstLine.textContent = lines[0];
                firstLine.setAttribute('aria-hidden', 'true');
                const accent = document.createElement('span');
                accent.className = 'hero-line hero-accent';
                accent.textContent = lines[1];
                accent.setAttribute('aria-hidden', 'true');
                element.setAttribute('aria-label', lines.join(' '));
                element.replaceChildren(firstLine, document.createTextNode(' '), accent);
            } else {
                element.textContent = value;
            }
        });
        document.querySelectorAll('[data-i18n-ph]').forEach(element => {
            const value = placeholders[lang][element.dataset.i18nPh];
            if (value) element.setAttribute('placeholder', value);
        });
        ['aria', 'alt'].forEach(attribute => {
            document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
                const value = translations[lang][element.getAttribute(`data-i18n-${attribute}`)];
                if (value) element.setAttribute(attribute === 'aria' ? 'aria-label' : 'alt', value);
            });
        });
        document.dispatchEvent(new CustomEvent('languagechange'));
    }
    setLanguage(currentLang);
})();
